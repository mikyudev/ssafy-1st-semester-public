# 부모클래스 
class Person:
    def walk(self):
        print('사람이 걷는대유')


# 자식클래스  |      클래스의 인자로 클래스를 받으면 상속받은거임 
class SuperMan(Person):
    def fly(slef):
        print('슈퍼맨이 난데이')

# 1. 오버라이딩 !!!!!!!!!!!!!!!!!!!!!!!!
    def walk(slef):  # 오버라이딩 == 메서드를 재정의 한다. !!!!!!!!!!!!!!!!!!!!!
        print('슈퍼맨이 뚜벅뚜벅 걷는데이') 



    

a = SuperMan() # 인스턴스 생성 -> 부모클래스 인스턴스 생성 할 필요가 없음 ㄷㄷ 
# 자식 클래스의 인스턴스를 생성해도 부모클래스의 메서드 호출이 가능 
a.walk()
a.fly()








