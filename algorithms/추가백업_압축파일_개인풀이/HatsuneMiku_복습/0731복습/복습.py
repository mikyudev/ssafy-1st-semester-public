'''클래스 정의'''
class SetMenu:
    # def __init__ = 생성자 매서드 (변수를 초기화 하기 위해)
    def __init__(self): # 항상 인자로 self 들어옴 
        self.potato = 100 # 인스턴스 변수(속성) , 필드 
        self.hambug = 300

    # 메서드 
    # append(), pop() ---> 호출할 수 있는 이유 : built - in scope 이기 떄문 
    def eat(self):
        print('햄버거 세트 맛있다')
        print(f'음 {self.potato + self.hambug}불이 들었네')

'''클래스 호출'''
# 인스턴스 생성  -> # 메서드 호출 가능 
sanghi = SetMenu()  # 변수 = 클래스명()
# 메서드 호출
sanghi.eat()

